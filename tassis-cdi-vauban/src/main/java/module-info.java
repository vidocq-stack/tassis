/**
 * CDI integration of Tassis: the injection of {@code JMSContext} (Jakarta Messaging 3.1 §12.4).
 * The CDI API is only needed where this module is used, hence {@code requires static}.
 */
module io.vidocq.tassis.cdi.vauban {
    requires transitive io.vidocq.tassis.core;

    requires static jakarta.cdi;
    requires static jakarta.inject;
    requires static jakarta.annotation;
    // Compile-only too: the service type of the generated provider below. Without Vauban at run
    // time the provides clause is inert, as nobody uses the service.
    requires static io.vidocq.vauban.api;

    // Generated by Vauban's annotation processor: instantiates, injects and invokes the beans of
    // the package from inside this module, so that no package needs to be opened to the container.
    provides io.vidocq.vauban.api.VaubanComponentProvider
            with io.vidocq.tassis.cdi.internal._VaubanComponents;

    exports io.vidocq.tassis.cdi;
}
